public class task04_datatypes {
    public static void main(String args[]){
        int a=5;//4 bytes=32 bits
        float b=10.5f;//4 bytes=32 bits
        double c=20.99;//8 bytes=64 bits
        char d='A';//2 bytes=16 bits
        boolean e=true;// 1 byte=8 bits
        String name="John";// variable length
        short n=100;//2 bytes=16 bits
        byte m=8;//1 byte=8 bits
        long o=100000L;//8 bytes=64 bits

        System.out.println("The value of a is: " + a);
        System.out.println("The value of b is: " + b);  
        System.out.println("The value of c is: " + c);
        System.out.println("The value of d is: " + d);
        System.out.println("The value of e is: " + e);
        System.out.println("The value of name is: " + name);
        System.out.println("The value of n is: " + n);
        System.out.println("The value of m is: " + m);
        System.out.println("The value of o is: " + o);
    }
}
